package com.revilo.gatesofavarice.item;

import java.util.List;
import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;

public final class GodsTomeOfKnowledgeItem extends Item {
    public GodsTomeOfKnowledgeItem(Properties properties) {
        super(properties);
    }

    @Override
    public boolean isFoil(ItemStack stack) {
        return true;
    }

    @Override
    public void appendHoverText(ItemStack stack, TooltipContext context, List<Component> tooltip, TooltipFlag flag) {
        tooltip.add(Component.literal("The Archive Keeper can reveal all knowledge within.").withStyle(ChatFormatting.LIGHT_PURPLE));
    }
}
